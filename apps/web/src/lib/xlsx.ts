/**
 * Minimal dependency-free .xlsx writer: multiple sheets, a few cell styles, formulas, column widths and a
 * frozen header. Formulas carry no cached value; fullCalcOnLoad makes the spreadsheet app compute them. Files are an uncompressed (stored) zip, which every spreadsheet app opens.
 */

export type CellStyle = 'text' | 'bold' | 'title' | 'subtitle' | 'header' | 'section' | 'note' | 'money' | 'percent' | 'decimal' | 'integer' | 'input'
export type CellValue = string | number | null
/** `f` is an Excel formula without the leading '='. */
export type Cell = CellValue | { v: CellValue; s: CellStyle } | { f: string; s: CellStyle }

export interface WorksheetSpec {
  name: string
  rows: Cell[][]
  /** Character widths per column. */
  widths?: number[]
  /** Rows above this index stay visible while scrolling (1-based count). */
  freezeRows?: number
}

// Order is the cellXfs index in styles.xml.
